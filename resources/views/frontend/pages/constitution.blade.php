                    <p>
                        The PGIMER, Chandigarh was the vision of late Sardar Partap Singh
                        Kairon, the Chief Minister of undivided Punjab and the distinguished
                        medical educationists of the state of Punjab. This institute was
                        started in 1962 and finally inaugurated by Pt Jawahar Lal Nehru,
                        the first Prime Minister of India on 7th July 1963 to provide high
                        quality patient care in the country and attain self-sufficiency in
                        postgraduate medical education to meet the country’s need for highly
                        qualified medical teachers in all medical and surgical fields.
                        The Institute was originally under the Government of undivided Punjab.
                        After the reorganization of the state, the administrative control of
                        the institute passed on to the Union Territory of Chandigarh in
                        November 1966. The Institute became an autonomous body under the Act
                        of Parliament in 1967 functioning under the Ministry of Health and
                        Family Welfare, Government of India.
                    </p>

                    <p>
                        In the finest global tradition of the reputed seats of learning,
                        which cherish links with their former students for mutual pride and
                        enrichment,and for the welfare of patients through their professional
