                    <h5 class="mb-4 mt-5">C. Other</h5>

                    <h5 class="mb-4 mt-5">MEETINGS:</h5>

                    <p>
                        There will be a minimum of one General Body Meeting and two Executive
                        Committee meetings in a year. Absence from three consecutive Executive
                        Committee meetings without prior intimation may lead to dropping of the
                        member from the Executive Committee. The vacancy thus created will be
                        filled by co-opting a member from the General Body with a consent of
                        2/3rd Majority of the executive committee.
                    </p>

                    <h5 class="mb-4 mt-5">11. PROCEDURE FOR CALLING OF MEETINGS:</h5>

                    <p>
                        The Secretary will call the meetings of the General Body. The place and
                        time of which will be fixed in consultation with the President. Agenda
                        for the meeting will be approved by the President and will accompany the
                        notice. Notice for the Executive Committee, however, can be given on
                        e-mail/phone or any other manner with approval of the Executive Committee.
                    </p>

                    <p>
                        Extraordinary General Body Meeting can be convened by the Executive
                        Committee and by a special requisition from at least 100 members.
                    </p>

                    <h5 class="mb-4 mt-5">12. QUORUM:</h5>

                    <p>
                        The Association will adopt presence of one-third of total members as
                        proper quorum in all meetings of the Executive Committee and one-fifth
                        of all members in case of the General Body meeting. In case the quorum
                        is inadequate, the meeting will be adjourned and re-convened after
                        15 minutes. The members present in the re-convened meeting will constitute
                        the quorum for that meeting. All resolutions will be passed by majority
                        of the members.
                    </p>

                    <h5 class="mb-4 mt-5">13. AMENDMENTS OF THE CONSTITUTION:</h5>

                    <p>
                        Proposals for amendments to the constitution may be submitted to the
                        Executive Committee by any member of PCAAS. Such proposals will be
                        discussed by the Executive Committee and presented in a General Body
                        meeting for which prior information will be provided at least six weeks
                        before the meeting. Amendments to the Constitution will be adopted by
                        two third majorities of the members present and voting.
                    </p>

                    <h5 class="mb-4 mt-5">14. FINANCIAL YEAR:</h5>

                    <p>
                        The financial year of the “PCAAS" will be from 1st April to 31st March
                        every year.
                    </p>

                    <h5 class="mb-4 mt-5">15. BANK OPERATION:</h5>

                    <p>
                        The authorised signatories to operate the bank accounts will be any two
                        of the three office bearers, i.e. the President, Secretary and Treasurer.
                        The accounts shall be maintained in any of the Nationalised Bank in
                        Chandigarh/Chandigarh
                    </p>

                    <h5 class="mb-4 mt-5">16. AUDITOR:</h5>

                    <p>
                        The Executive Body will appoint an Auditor (Chartered Accountant) who
                        will submit his report to the Treasurer for presentation to the General
                        Body Every Year
                    </p>

                    <h5 class="mb-4 mt-5">17. DONATION:</h5>

                    <p>
                        Donation of any amount in cash (as per the provisions of income tax rules)
                        and/or kind may be accepted by the Association. Against the proper receipt
                        and shall be included in Audit report.
                    </p>

                    <h5 class="mb-4 mt-5">18. ELECTION PROCEDURE:</h5>

                    <h5 class="mb-4 mt-5">18.1</h5>

                    <p>
                        Entire proceeding of the election to the Executive Committee will be
                        conducted by an Election Committee of 3 persons nominated by the Executive
                        Committee. Out of these, one shall be the President of Election Committee
                        and two other, the members. None of the Executive committee existing shall
                        be the appointed as Election Staff. The Election shall take place under
                        the supervision of PATRON and ADVISOR
                    </p>

                    <h5 class="mb-4 mt-5">18.2</h5>

                    <p>
                        Election dates will be determined by the Executive Committee along with
                        the members of Election Committee.
                    </p>

                    <h5 class="mb-4 mt-5">18.3</h5>

                    <p>
                        Election will be held in a General Body meeting called for this purpose
                        by the members present. President of the Election Committee will notify
                        elections to various posts by giving at least 3 weeks prior notice.
                        Election Committee will receive the names of the desirous candidates
                        from amongst the members of the General Body of the appropriate Groups.
                        Date for receiving and withdrawal of the nominations will be announced
                        in the initial notice.
                    </p>

                    <p>
                        Nominations thus received will be scrutinized by the Election Committee.
                        If there are more than one candidate for a particular post, election will
                        take place by a secret ballot in the General Body Meeting called for this
                        purpose. After counting of the votes, the result will be declared in the
                        same meeting.
                    </p>

